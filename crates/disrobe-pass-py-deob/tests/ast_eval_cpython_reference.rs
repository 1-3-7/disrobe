#![allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]
use std::path::{Path, PathBuf};

use disrobe_pass_py_deob::ast_eval::{EvalReport, evaluate_source};
use ruff_python_ast::{Expr, ExprTuple, ExprUnaryOp, UnaryOp};
use ruff_python_parser::{Mode, ParseOptions, parse};

const PROBE_CALL: &str = "_probe";
const FOLDED_EXPECTED: usize = 323;

fn reference_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("ast_eval_gate")
        .join("cpython_reference.tsv")
}

#[derive(Debug)]
struct Row {
    expression: String,
    expected: Option<String>,
}

fn load_reference() -> Vec<Row> {
    let path: PathBuf = reference_path();
    let raw: String = std::fs::read_to_string(&path).unwrap_or_else(|e: std::io::Error| {
        panic!(
            "the CPython reference table is the only independent grader for the Python AST \
             evaluator; regenerate it with `python {}` and commit the result. read {}: {e}",
            Path::new("crates")
                .join("disrobe-pass-py-deob")
                .join("tests")
                .join("ast_eval_gate")
                .join("make_reference.py")
                .display(),
            path.display()
        )
    });
    let mut rows: Vec<Row> = Vec::new();
    let mut interpreter: Option<String> = None;
    for line in raw.lines() {
        if let Some(banner) = line.strip_prefix("# generated by make_reference.py under ") {
            interpreter = Some(banner.to_owned());
            continue;
        }
        if line.trim().is_empty() {
            continue;
        }
        let (expression, tail): (&str, &str) = line
            .split_once('\t')
            .unwrap_or_else(|| panic!("reference row is not tab separated: {line}"));
        let expected: Option<String> = if tail == "!ERROR" || tail.starts_with("!ERROR\t") {
            None
        } else {
            Some(tail.to_owned())
        };
        rows.push(Row {
            expression: expression.to_owned(),
            expected,
        });
    }
    assert!(
        interpreter.is_some(),
        "{} must record the interpreter that produced it",
        path.display()
    );
    assert!(
        rows.len() > 300,
        "{} carries only {} probes; the table is truncated",
        path.display(),
        rows.len()
    );
    rows
}

fn fold_probe(expression: &str) -> String {
    let source: String = format!("x = {PROBE_CALL}({expression})\n");
    let evaluated: Result<(String, EvalReport), disrobe_pass_py_deob::Error> =
        evaluate_source(&source);
    let (folded, _report): (String, EvalReport) = evaluated.unwrap_or_else(|e| {
        panic!("evaluate_source rejected the probe wrapper for {expression}: {e:?}")
    });
    let trimmed: &str = folded.trim();
    let opener: String = format!("x = {PROBE_CALL}(");
    trimmed
        .strip_prefix(opener.as_str())
        .and_then(|rest: &str| rest.strip_suffix(')'))
        .unwrap_or_else(|| {
            panic!("probe wrapper was rewritten beyond recognition for {expression}: {trimmed}")
        })
        .to_owned()
}

fn is_literal(source: &str) -> bool {
    let Ok(parsed) = parse(source, ParseOptions::from(Mode::Expression)) else {
        return false;
    };
    let ruff_python_ast::Mod::Expression(module) = parsed.into_syntax() else {
        return false;
    };
    literal_expr(&module.body)
}

fn literal_expr(expr: &Expr) -> bool {
    match expr {
        Expr::NumberLiteral(_)
        | Expr::StringLiteral(_)
        | Expr::BytesLiteral(_)
        | Expr::BooleanLiteral(_)
        | Expr::NoneLiteral(_) => true,
        Expr::UnaryOp(ExprUnaryOp { op, operand, .. }) => {
            matches!(op, UnaryOp::USub | UnaryOp::UAdd) && literal_expr(operand)
        }
        Expr::List(list) => list.elts.iter().all(literal_expr),
        Expr::Tuple(ExprTuple { elts, .. }) => elts.iter().all(literal_expr),
        _ => false,
    }
}

#[test]
fn folded_values_match_cpython_and_refusals_stay_unfolded() {
    let rows: Vec<Row> = load_reference();
    let mut folded: usize = 0;
    let mut wrong: Vec<String> = Vec::new();
    for row in &rows {
        let rendered: String = fold_probe(&row.expression);
        match row.expected.as_deref() {
            Some(reference) => {
                if rendered == reference {
                    folded += 1;
                } else if is_literal(&rendered) {
                    wrong.push(format!(
                        "{expr}: CPython says {reference}, disrobe folded to {rendered}",
                        expr = row.expression
                    ));
                }
            }
            None => {
                if is_literal(&rendered) {
                    wrong.push(format!(
                        "{expr}: CPython raises, disrobe folded to {rendered}",
                        expr = row.expression
                    ));
                }
            }
        }
    }
    assert!(
        wrong.is_empty(),
        "the AST evaluator produced {n} value(s) that disagree with CPython:\n{joined}",
        n = wrong.len(),
        joined = wrong.join("\n")
    );
    assert_eq!(
        folded,
        FOLDED_EXPECTED,
        "the evaluator folds {folded} of {total} committed CPython probes; FOLDED_EXPECTED is \
         {FOLDED_EXPECTED}. Widening or narrowing the evaluator has to move this number in the \
         same change.",
        total = rows.len()
    );
}

#[test]
fn every_probe_that_folds_is_reachable_through_the_source_cleanup_entry_point() {
    let source: &str = "key = 'shift-%02x' % 27\nblob = bytes.fromhex('4869').decode('latin1')\n\
                        tag = f'{len(blob):03d}'\n";
    let (folded, report): (String, EvalReport) =
        evaluate_source(source).expect("evaluate the caller-shaped sample");
    assert!(
        folded.contains("'shift-1b'"),
        "printf formatting must reach the public evaluator entry point: {folded}"
    );
    assert!(
        folded.contains("'Hi'"),
        "latin-1 decode must reach the public evaluator entry point: {folded}"
    );
    assert!(
        folded.contains("'002'"),
        "f-string folding must reach the public evaluator entry point: {folded}"
    );
    assert!(report.exprs_folded >= 3, "report undercounts: {report:?}");
}
