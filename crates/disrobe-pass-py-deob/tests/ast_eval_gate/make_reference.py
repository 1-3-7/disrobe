"""Regenerate the CPython reference table for the Python AST evaluator gate.

Run with the interpreter whose semantics the table records:

    python crates/disrobe-pass-py-deob/tests/ast_eval_gate/make_reference.py

Each output row is `expression<TAB>repr(value)`, or `expression<TAB>!ERROR<TAB>detail`
when the expression raises. The row values come from the interpreter, never from
disrobe, so the table is an independent reference for the evaluator.
"""

from __future__ import annotations

import platform
import sys
from pathlib import Path

HERE: Path = Path(__file__).resolve().parent
PROBES: Path = HERE / "probes.txt"
TABLE: Path = HERE / "cpython_reference.tsv"


def evaluate(expression: str, /) -> str:
    try:
        value: object = eval(expression, {"__builtins__": __builtins__}, {})
    except Exception as exc:
        return f"{expression}\t!ERROR\t{type(exc).__name__}: {exc}"
    return f"{expression}\t{value!r}"


def main() -> int:
    rows: list[str] = [
        f"# generated by make_reference.py under CPython {platform.python_version()}"
    ]
    seen: set[str] = set()
    for raw in PROBES.read_text(encoding="utf-8").splitlines():
        expression: str = raw.strip()
        if not expression or expression.startswith("#"):
            continue
        if expression in seen:
            raise SystemExit(f"duplicate probe: {expression}")
        seen.add(expression)
        rows.append(evaluate(expression))
    TABLE.write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rows) - 1} rows to {TABLE}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
