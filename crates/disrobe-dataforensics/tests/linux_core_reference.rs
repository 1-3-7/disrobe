#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
use std::collections::{BTreeMap, BTreeSet};
use std::io::Read;
use std::path::{Path, PathBuf};

use disrobe_dataforensics::crash::{
    Architecture, CrashFormat, CrashLimits, CrashReport, FaultKind, ModuleReport, ThreadReport,
    inspect,
};

const PROGRAMS: [&str; 4] = ["segv", "abort", "threads", "stack"];
const MAX_INFLATED: u64 = 128 * 1024 * 1024;

fn corpus() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../corpus/crash/linux/runner")
}

fn inflate(name: &str) -> Vec<u8> {
    let path: PathBuf = corpus().join(name);
    let packed: Vec<u8> = std::fs::read(&path)
        .unwrap_or_else(|error| panic!("runner fixture {} is required: {error}", path.display()));
    let mut out: Vec<u8> = Vec::new();
    flate2::read::GzDecoder::new(packed.as_slice())
        .take(MAX_INFLATED)
        .read_to_end(&mut out)
        .expect("gzip fixture");
    out
}

#[derive(Debug, Default)]
struct GdbView {
    command_line: String,
    signal: String,
    current: u32,
    threads: BTreeSet<u32>,
    frame_pc: BTreeMap<u32, u64>,
    registers: BTreeMap<String, u64>,
    libraries: Vec<(u64, u64, String)>,
}

fn hex(text: &str) -> u64 {
    u64::from_str_radix(text.trim_start_matches("0x"), 16).expect("gdb hex value")
}

fn lwp(text: &str) -> Option<u32> {
    let start: usize = text.find("(LWP ")? + 5;
    let end: usize = start + text[start..].find(')')?;
    text[start..end].parse().ok()
}

fn gdb_view(text: &str) -> GdbView {
    let mut view: GdbView = GdbView::default();
    let mut thread: Option<u32> = None;
    let mut in_registers: bool = false;
    let mut in_libraries: bool = false;
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("Core was generated by `") {
            rest.trim_end_matches("'.")
                .clone_into(&mut view.command_line);
        } else if let Some(rest) = line.strip_prefix("Program terminated with signal ") {
            rest.split(',').next().unwrap().clone_into(&mut view.signal);
        } else if line.starts_with("* ") && line.contains("Thread 0x") {
            view.current = lwp(line).unwrap();
            view.threads.insert(view.current);
        } else if line.starts_with("  ")
            && line
                .trim_start()
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_digit())
            && line.contains("Thread 0x")
        {
            view.threads.insert(lwp(line).unwrap());
        } else if line.starts_with("Thread ") && line.ends_with("):") {
            thread = lwp(line);
        } else if let Some(rest) = line.strip_prefix("#0  ") {
            let address: Option<&str> = rest
                .split_once(" in ")
                .map(|(address, _)| address)
                .filter(|address: &&str| address.starts_with("0x"));
            if let (Some(owner), Some(address)) = (thread, address) {
                view.frame_pc.insert(owner, hex(address));
            }
            thread = None;
        } else if line.starts_with("rax ") {
            in_registers = true;
        } else if line.starts_with("From ") && line.contains("Shared Object Library") {
            in_registers = false;
            in_libraries = true;
            continue;
        }
        if in_registers {
            let fields: Vec<&str> = line.split_whitespace().collect();
            if fields.len() >= 2 && fields[1].starts_with("0x") {
                view.registers.insert(fields[0].to_owned(), hex(fields[1]));
            }
        }
        if in_libraries {
            let fields: Vec<&str> = line.split_whitespace().collect();
            if fields.len() >= 4 && fields[0].starts_with("0x") {
                view.libraries.push((
                    hex(fields[0]),
                    hex(fields[1]),
                    fields[fields.len() - 1].to_owned(),
                ));
            }
        }
    }
    view
}

fn signal_number(name: &str) -> u32 {
    match name {
        "SIGILL" => 4,
        "SIGABRT" => 6,
        "SIGBUS" => 7,
        "SIGFPE" => 8,
        "SIGSEGV" => 11,
        other => panic!("gdb named a signal this grader does not map: {other}"),
    }
}

fn grade(report: &CrashReport, view: &GdbView, graded: &mut usize) -> Vec<String> {
    let mut wrong: Vec<String> = Vec::new();
    let mut check = |ok: bool, what: String| {
        *graded += 1;
        if !ok {
            wrong.push(what);
        }
    };
    check(
        report.format == CrashFormat::ElfCore,
        format!("format {:?}", report.format),
    );
    check(
        report.architecture == Architecture::X86_64,
        format!("architecture {:?}", report.architecture),
    );
    check(
        report.process.command_line.as_deref().map(str::trim) == Some(view.command_line.as_str()),
        format!(
            "command line {:?} against gdb {:?}",
            report.process.command_line, view.command_line
        ),
    );
    let fault = report.fault.as_ref();
    check(
        fault.is_some_and(|fault| fault.kind == FaultKind::Signal),
        format!("fault kind {fault:?}"),
    );
    check(
        fault.is_some_and(|fault| fault.code == signal_number(&view.signal)),
        format!(
            "signal {:?} against gdb {}",
            fault.map(|fault| fault.code),
            view.signal
        ),
    );
    check(
        fault.and_then(|fault| fault.name) == Some(view.signal.as_str()),
        format!(
            "signal name {:?} against gdb {}",
            fault.and_then(|fault| fault.name),
            view.signal
        ),
    );
    check(
        fault.and_then(|fault| fault.thread_id) == Some(view.current),
        format!(
            "faulting thread {:?} against gdb LWP {}",
            fault.and_then(|fault| fault.thread_id),
            view.current
        ),
    );
    let ids: BTreeSet<u32> = report
        .threads
        .iter()
        .map(|thread: &ThreadReport| thread.id)
        .collect();
    check(
        ids == view.threads,
        format!("threads {ids:?} against gdb {:?}", view.threads),
    );
    let crashed: Vec<u32> = report
        .threads
        .iter()
        .filter(|thread: &&ThreadReport| thread.crashed)
        .map(|thread: &ThreadReport| thread.id)
        .collect();
    check(
        crashed == [view.current],
        format!(
            "crashed threads {crashed:?} against gdb LWP {}",
            view.current
        ),
    );
    for (owner, pc) in &view.frame_pc {
        let thread: Option<&ThreadReport> = report
            .threads
            .iter()
            .find(|thread: &&ThreadReport| thread.id == *owner);
        check(
            thread.and_then(|thread| thread.instruction_pointer) == Some(*pc),
            format!(
                "LWP {owner} pc {:?} against gdb {pc:#x}",
                thread.and_then(|thread| thread.instruction_pointer)
            ),
        );
    }
    let current: Option<&ThreadReport> = report
        .threads
        .iter()
        .find(|thread: &&ThreadReport| thread.id == view.current);
    for (name, value) in &view.registers {
        let recovered: Option<u64> = current.and_then(|thread| {
            thread
                .registers
                .iter()
                .find(|register| register.name == name.as_str())
                .map(|register| register.value)
        });
        check(
            recovered == Some(*value),
            format!("register {name} {recovered:?} against gdb {value:#x}"),
        );
    }
    for (from, to, path) in &view.libraries {
        let covered: bool = report.modules.iter().any(|module: &ModuleReport| {
            module.loader_name.as_deref() == Some(path.as_str())
                && module.base <= *from
                && *to <= module.base.saturating_add(module.size)
        });
        check(
            covered,
            format!("library {path} {from:#x}..{to:#x} has no module covering it"),
        );
    }
    wrong
}

fn view_and_report(program: &str) -> (Vec<u8>, GdbView) {
    let core: Vec<u8> = inflate(&format!("{program}.core.gz"));
    let text: String =
        String::from_utf8(inflate(&format!("{program}.gdb.txt.gz"))).expect("gdb text");
    (core, gdb_view(&text))
}

#[test]
fn kernel_cores_read_the_same_as_gdb() {
    let mut graded: usize = 0;
    let mut failures: Vec<String> = Vec::new();
    for program in PROGRAMS {
        let (core, view) = view_and_report(program);
        assert!(
            view.registers.len() >= 20,
            "{program}: gdb printed {} registers",
            view.registers.len()
        );
        assert!(
            !view.libraries.is_empty(),
            "{program}: gdb listed no shared library"
        );
        let report: CrashReport =
            inspect(&core, &CrashLimits::default()).expect("kernel core parses");
        for wrong in grade(&report, &view, &mut graded) {
            failures.push(format!("{program}: {wrong}"));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {graded} gdb facts differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
    assert!(graded >= 150, "only {graded} gdb facts were graded");
}

#[test]
fn a_changed_register_in_the_core_is_caught() {
    let (mut core, view) = view_and_report("threads");
    let rip: u64 = view.registers["rip"];
    let needle: [u8; 8] = rip.to_le_bytes();
    let at: usize = core
        .windows(8)
        .position(|window: &[u8]| window == needle)
        .expect("the crashing rip is stored in the core");
    core[at] ^= 0x40;
    let report: CrashReport = inspect(&core, &CrashLimits::default()).expect("mutated core parses");
    let mut graded: usize = 0;
    let wrong: Vec<String> = grade(&report, &view, &mut graded);
    assert!(
        wrong
            .iter()
            .any(|line: &String| line.contains("register rip") || line.contains("pc ")),
        "a flipped rip byte went unnoticed: {wrong:?}"
    );
}

#[test]
fn a_changed_gdb_fact_is_caught() {
    let (core, mut view) = view_and_report("segv");
    let report: CrashReport = inspect(&core, &CrashLimits::default()).expect("kernel core parses");
    view.current += 1;
    let mut graded: usize = 0;
    assert!(!grade(&report, &view, &mut graded).is_empty());
}
