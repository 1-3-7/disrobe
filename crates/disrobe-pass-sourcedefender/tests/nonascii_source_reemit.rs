#[test]
fn decrypt_pye_preserves_non_ascii_and_escape_bytes_exactly() {
    let Ok(decrypted): Result<DecryptedPye> = decrypt_pye(NONASCII_LEGACY_PYE, "unicode_mod.pye")
    else {
        unreachable!("decrypt_pye must peel the independently crafted legacy sample")
    };
    let Some(envelope): Option<PyeEnvelope> = decrypted.envelope else {
        unreachable!("the aes-ctr plaintext must parse as a msgpack envelope")
    };
    let PyeCodePayload::Source(ref code): PyeCodePayload = envelope.original_code else {
        unreachable!(
            "free-version .pye carries its source under a msgpack string, not marshal bytes"
        )
    };
    assert_eq!(
        code.as_bytes(),
        EXPECTED_SOURCE.as_bytes(),
        "recovered source must be byte-identical to the original plaintext, high bytes and \
         backslash escapes included\nrecovered:\n{code}\nexpected:\n{EXPECTED_SOURCE}"
    );
}

#[test]
fn decrypt_pye_to_source_reemits_non_ascii_and_escapes_byte_for_byte() {
    let Ok(out): Result<SourceRecoverOutput> = decrypt_pye_to_source(
        NONASCII_LEGACY_PYE,
        "unicode_mod.pye",
        SourceRecoverOpts::default(),
    ) else {
        unreachable!("decrypt_pye_to_source must recover the inline source")
    };
    let Some(recovered): Option<String> = out.recovered_source else {
        unreachable!("free-version inline source must be recovered as a source string")
    };
    assert_eq!(recovered.as_bytes(), EXPECTED_SOURCE.as_bytes());
    assert_eq!(out.marshal_size, 0);
    assert!(out.code_object_summary.is_empty());
}
