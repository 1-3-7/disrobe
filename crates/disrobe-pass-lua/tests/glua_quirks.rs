#![allow(clippy::expect_used, clippy::panic, clippy::unwrap_used)]

use disrobe_pass_lua::LuaDialect;
use disrobe_pass_lua::reader::{common::LuaChunk, glua};

#[test]
fn glua_detects_prefix_byte() {
    let mut bytes: Vec<u8> = Vec::with_capacity(64);
    bytes.push(0x1C);
    bytes.extend_from_slice(&[
        0x1B, b'L', b'u', b'a', 0x51, 0x00, 0x01, 0x04, 0x04, 0x04, 0x08, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ]);
    assert!(glua::looks_like_glua(&bytes));
    let chunk: LuaChunk = glua::read(&bytes).expect("parse glua");
    assert_eq!(chunk.dialect, LuaDialect::GLua);
}

#[test]
fn glua_passes_through_when_no_prefix() {
    let bytes: &[u8] = &[
        0x1B, b'L', b'u', b'a', 0x51, 0x00, 0x01, 0x04, 0x04, 0x04, 0x08, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ];
    assert!(!glua::looks_like_glua(bytes));
    let chunk: LuaChunk = glua::read(bytes).expect("parse base lua51");
    assert_eq!(chunk.dialect, LuaDialect::GLua);
}
