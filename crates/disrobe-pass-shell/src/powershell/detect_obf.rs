#[must_use]
pub fn obfuscator_detect(input: &str) -> ObfuscatorDetection {
    let mut markers: Vec<String> = Vec::new();
    let mut scores: Vec<(PsObfuscator, f32)> = Vec::new();
    for sig in SIGNATURES.iter() {
        if sig.re.is_match(input) {
            markers.push(sig.marker.to_owned());
            match scores
                .iter_mut()
                .find(|(f, _): &&mut (PsObfuscator, f32)| *f == sig.family)
            {
                Some((_, acc)) => *acc += sig.weight,
                None => scores.push((sig.family, sig.weight)),
            }
        }
    }
    for entry in &mut scores {
        entry.1 = entry.1.min(1.0);
    }
    scores.sort_by(|a: &(PsObfuscator, f32), b: &(PsObfuscator, f32)| {
        b.1.partial_cmp(&a.1).unwrap_or(std::cmp::Ordering::Equal)
    });
    let (obfuscator, confidence): (PsObfuscator, f32) =
        scores.first().copied().unwrap_or((PsObfuscator::None, 0.0));
    ObfuscatorDetection {
        obfuscator,
        confidence,
        markers,
        ranked: scores,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_isesteroids_signature_block() {
        let src: &str =
            "Write-Host 'hi'\n# SIG # Begin signature block\nAAAA\n# SIG # End signature block\n";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert_eq!(d.obfuscator, PsObfuscator::IseSteroids);
        assert!(d.confidence >= 0.6, "confidence={}", d.confidence);
    }

    #[test]
    fn detects_hex_encoder() {
        let src: &str = "$x | ForEach-Object {[Char]([Convert]::ToInt16($_,16))} | IEX";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert_eq!(d.obfuscator, PsObfuscator::EncodedHex);
    }

    #[test]
    fn detects_bxor_encoder() {
        let src: &str = "(72,73,74 | %{[char]($_ -bxor 42)}) -join ''";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert_eq!(d.obfuscator, PsObfuscator::EncodedBxor);
    }

    #[test]
    fn detects_iex_comspec_indirection() {
        let src: &str = "&( $env:ComSpec[4,15,25]-Join'')( $payload )";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert_eq!(d.obfuscator, PsObfuscator::IexIndirection);
        assert!(d.markers.iter().any(|m: &String| m == "iex-comspec"));
    }

    #[test]
    fn detects_mdr_variable_indirection() {
        let src: &str = "((Variable '*mdr*').Name[3,11,2]-Join'')( $sc )";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert_eq!(d.obfuscator, PsObfuscator::IexIndirection);
    }

    #[test]
    fn detects_base64_encoded_command() {
        let src: &str = "powershell -nop -enc QQBBAEEAQQBBAEEAQQBBAEEAQQBB";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert_eq!(d.obfuscator, PsObfuscator::Base64Encoded);
    }

    #[test]
    fn plain_script_scores_none() {
        let src: &str = "Write-Host 'hello world'\nGet-Process | Sort-Object CPU\n";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert_eq!(d.obfuscator, PsObfuscator::None);
        assert!(d.confidence.abs() < f32::EPSILON);
    }

    #[test]
    fn ranked_breakdown_orders_by_confidence() {
        let src: &str =
            "# SIG # Begin signature block\n$x=([char]73);IEX (Variable '*mdr*').Value\n";
        let d: ObfuscatorDetection = obfuscator_detect(src);
        assert!(!d.ranked.is_empty());
        for win in d.ranked.windows(2) {
            assert!(win[0].1 >= win[1].1, "ranked not sorted: {:?}", d.ranked);
        }
    }
}
