use std::sync::LazyLock;

use regex::Regex;
use serde::Serialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub enum PsObfuscator {
    IseSteroids,
    InvokeObfuscationToken,
    InvokeObfuscationString,
    EncodedHex,
    EncodedOctal,
    EncodedBinary,
    EncodedAscii,
    EncodedBxor,
    EncodedSpecialChar,
    EncodedWhitespace,
    Base64Encoded,
    GzipCompressed,
    SecureString,
    IexIndirection,
    None,
}

#[derive(Debug, Clone, Serialize)]
pub struct ObfuscatorDetection {
    pub obfuscator: PsObfuscator,
    pub confidence: f32,
    pub markers: Vec<String>,
    pub ranked: Vec<(PsObfuscator, f32)>,
}

struct SignatureSpec {
    family: PsObfuscator,
    marker: &'static str,
    weight: f32,
    pattern: &'static str,
}

struct Signature {
    family: PsObfuscator,
    marker: &'static str,
    weight: f32,
    re: Regex,
}

const fn sig(
    family: PsObfuscator,
    marker: &'static str,
    weight: f32,
    pattern: &'static str,
) -> SignatureSpec {
    SignatureSpec {
        family,
        marker,
        weight,
        pattern,
    }
}

static SIGNATURES: LazyLock<Vec<Signature>> = LazyLock::new(|| {
    SIGNATURE_SPECS
        .iter()
        .map(|s: &SignatureSpec| Signature {
            family: s.family,
            marker: s.marker,
            weight: s.weight,
            re: crate::regex_util::safe_regex(s.pattern),
        })
        .collect()
});

