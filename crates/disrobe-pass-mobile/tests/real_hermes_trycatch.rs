fn report() -> DecompileReport {
    let mut hasher: Sha256 = Sha256::new();
    hasher.update(TRYCATCH_HBC);
    let digest: [u8; 32] = hasher.finalize().into();
    let digest_hex: String = digest.iter().fold(
        String::with_capacity(digest.len() * 2),
        |mut acc: String, b: &u8| {
            use std::fmt::Write as _;
            let _: std::fmt::Result = write!(acc, "{b:02x}");
            acc
        },
    );
    assert_eq!(
        digest_hex, TRYCATCH_HBC_SHA256,
        "the embedded fixture must be exactly the bytes {TRYCATCH_HERMESC_PROVENANCE} produced"
    );
    let module: HermesModule = parse_hermes_module(TRYCATCH_HBC)
        .unwrap_or_else(|error: disrobe_pass_mobile::Error| panic!("parse: {error}"));
    decompile_hermes_module(&module)
}

fn function<'a>(report: &'a DecompileReport, name: &str) -> &'a DecompiledFunction {
    report
        .functions
        .iter()
        .find(|f: &&DecompiledFunction| f.name == name)
        .unwrap_or_else(|| panic!("function {name} not recovered"))
}

fn parses_as_javascript(src: &str) -> bool {
    let allocator: Allocator = Allocator::default();
    let source_type: SourceType = SourceType::from_path("recovered.js").unwrap_or_default();
    let parsed: oxc_parser::ParserReturn<'_> = Parser::new(&allocator, src, source_type).parse();
    parsed.errors.is_empty() && !parsed.panicked
}

fn eval_capture(program: &str) -> Option<String> {
    let mut context: Context = Context::default();
    {
        let runtime: &mut boa_engine::vm::RuntimeLimits = context.runtime_limits_mut();
        runtime.set_loop_iteration_limit(2_000_000);
        runtime.set_recursion_limit(1_500);
        runtime.set_stack_size_limit(50_000);
    }
    let harness: String = format!(
        "var __out = []; var print = function(v){{ __out.push(String(v)); }};\n{program}\n__out.join('\\u0001');"
    );
    let value: boa_engine::JsValue = context.eval(Source::from_bytes(harness.as_bytes())).ok()?;
    value
        .as_string()
        .map(boa_engine::JsString::to_std_string_escaped)
}

#[test]
fn hbc_v96_try_catch_structures_into_a_real_try_statement() {
    let decompiled: DecompileReport = report();
    let risky: &DecompiledFunction = function(&decompiled, "riskyDivide");
    assert!(
        risky.structured,
        "declined: {:?}\nsrc:\n{}",
        risky.structure_decline, risky.source
    );
    assert_eq!(risky.structure_decline, None);
    assert!(risky.has_try_catch);
    assert!(
        risky.source.contains("try {") && risky.source.contains("} catch ($exc) {"),
        "src:\n{}",
        risky.source
    );
    assert!(
        !risky.source.contains("goto ") && !risky.source.contains("unstructured ("),
        "src:\n{}",
        risky.source
    );
    assert!(
        parses_as_javascript(&risky.source),
        "src:\n{}",
        risky.source
    );
}

