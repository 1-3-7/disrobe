#[test]
fn hbc_v96_try_catch_is_behaviorally_correct_against_a_real_js_engine() {
    let decompiled: DecompileReport = report();
    let recovered_src: String = function(&decompiled, "riskyDivide").source.clone();

    let divides_cleanly: String = format!("{recovered_src}\nprint(riskyDivide(10, 2));");
    let divides_by_zero: String = format!("{recovered_src}\nprint(riskyDivide(10, 0));");
    let original_clean: String = format!("{TRYCATCH_JS_SOURCE}\nprint(riskyDivide(10, 2));");
    let original_zero: String = format!("{TRYCATCH_JS_SOURCE}\nprint(riskyDivide(10, 0));");

    let want_clean: String = eval_capture(&original_clean).expect("original divides cleanly");
    let got_clean: String = eval_capture(&divides_cleanly).expect("recovered divides cleanly");
    assert_eq!(
        want_clean, got_clean,
        "riskyDivide(10, 2): recovered try body diverged from the original\nsrc:\n{recovered_src}"
    );

    let want_zero: String = eval_capture(&original_zero).expect("original throws and catches");
    let got_zero: String = eval_capture(&divides_by_zero).expect("recovered throws and catches");
    assert_eq!(
        want_zero, got_zero,
        "riskyDivide(10, 0): recovered catch body diverged from the original\nsrc:\n{recovered_src}"
    );
    assert_eq!(want_clean, "5");
    assert_eq!(want_zero, "-1");
}

#[test]
fn correctness_oracle_rejects_a_try_catch_that_never_assigns_the_fallback() {
    let broken: &str = "function riskyDivide(a, b) {\n  var result;\n  try {\n    if (b === 0) { throw new Error(\"div0\"); }\n    result = a / b;\n  } catch (e) {\n  }\n  return result;\n}\nprint(riskyDivide(10, 0));";
    let original: String = format!("{TRYCATCH_JS_SOURCE}\nprint(riskyDivide(10, 0));");
    let want: String = eval_capture(&original).expect("original evaluates");
    let got: String = eval_capture(broken).expect("broken variant evaluates");
    assert_ne!(
        want, got,
        "a catch body that drops the fallback assignment must NOT pass the differential, proving \
         the oracle measures the caught-path behavior and not merely that a catch clause exists"
    );
}

